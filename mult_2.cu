constexpr char pack_elem(char is_positive, char y, char x)
{
    return (is_positive << 7) | (y << 3) | x;
}

inline __device__ constexpr void unpack_elem_into(
    const char packed,
    char &sign,
    char &y,
    char &x
) {
    sign = (packed & 0b10000000) ? 1 : -1;
    y    = (packed & 0b00111000) >> 3;
    x    = (packed & 0b00000111);
}

