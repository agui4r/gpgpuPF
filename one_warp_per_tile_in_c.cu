__global__ void mult_2_kernel(
    const float * __restrict__ mat_a,
    const float * __restrict__ mat_b,
    float * __restrict__ mat_c,
    int N)
{
    int tileX = blockIdx.x;
    int tileY = blockIdx.y;

    const float *Ap = mat_a + (tileY*4)*N;
    const float *Bp = mat_b + (tileX*5);
    float       *Cp = mat_c + (tileY*4)*N + tileX*5;

    // 20 + 25 + 20 = 65 floats  → caben en registros ?
    float Areg[20], Breg[25], Acc[20] = {0.f};
    int row = threadIdx.x / 5;
    int col = threadIdx.x % 5;

    #pragma unroll 1
    for (int offset = 0; offset < N; offset += 5)
    {
        if (threadIdx.x < 20)
        {
           Areg[threadIdx.x] = Ap[row * N + col + offset];
        }
        __syncthreads();

        if (threadIdx.x < 25)
        {
            Breg[threadIdx.x] = Bp[(row + offset) * N + col];
        }
        __syncthreads();

        // ----------  rank-76  ---------------------------------
        #pragma unroll
        for (int r = 0; r < 76; ++r){
            float aLin = 0.f, bLin = 0.f;
            #pragma unroll
            for(int t=0;t<20;++t) aLin += P[r][t] * Areg[t];
            #pragma unroll
            for(int t=0;t<25;++t) bLin += Q[r][t] * Breg[t];
            float m = aLin * bLin;
            #pragma unroll
            for(int t=0;t<20;++t) Acc[t] += R[r][t] * m;
        }
        __syncthreads();
    }

    if (threadIdx.x < 20)
    {
        C[row * N + col] = Acc[threadIdx.x];
    }
}

void mult_2(const float* mat_a, const float* mat_b, float* mat_c, int N)
{
    dim3 gridDim(N/5, N/4);
    mult_2_kernel<<<gridDim, 32>>>(mat_a, mat_b, mat_c, N);
    CUDA_CHK(cudaGetLastError());
    CUDA_CHK(cudaDeviceSynchronize());
}
