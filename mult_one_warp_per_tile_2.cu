__global__ void mult_one_warp_per_tile_2_kernel(
    const float * __restrict__ mat_a,
    const float * __restrict__ mat_b,
    float * __restrict__ mat_c,
    int N)
{
    int tid = threadIdx.x;

    int tileX = blockIdx.x;
    int tileY = blockIdx.y;
    
    __shared__ float CShared[4][5];
    if (tid < 20) CShared[tid / 5][tid % 5] = 0.0f;

    const float *Aptr = mat_a + tileY * N * 4 + tid * 5;
    const float *Bptr = mat_b + tileX * 5 + tid * N * 5;

    float Areg[4][5], Breg[5][5], Creg[4][5];
    for (int phase = 0; phase < (N / 5) / blockDim.x; phase++)
    {
        for (int y = 0; y < 4; y++)
        {
            for (int x = 0; x < 5; x++)
            {
                Areg[y][x] = Aptr[y * N + x];
            }
        }
        for (int y = 0; y < 5; y++)
        {
            for (int x = 0; x < 5; x++)
            {
                Breg[y][x] = Bptr[y * N + x];
            }
        }

        deepmatmul_2(Areg, Breg, Creg);
        __syncwarp();

        for (int y = 0; y < 4; y++) for (int x = 0; x < 5; x++)
            atomicAdd(&CShared[y][x], Creg[y][x]);

        // // Hago __shfl_down_sync para acumular todos los acc locales de cada thread en el acc local del thread 0
        // for (int shuffle_offset = 16; shuffle_offset; shuffle_offset >>= 1)
        // {
        //     #pragma unroll
        //     for (int y = 0; y < 4; y++)
        //     {
        //         for (int x = 0; x < 5; x++)
        //         {
        //             Creg[y][x] += __shfl_down_sync(0xffffffff, Creg[y][x], shuffle_offset);
        //         }
        //     }
        // }
        //
        // // Como solo el thread 0 tiene en su `Acc` el resultado de esta iteracion, solo lo puede copiar el
        // if (tid == 0)
        // {
        //     #pragma unroll
        //     for (int y = 0; y < 4; y++)
        //     {
        //         for (int x = 0; x < 5; x++)
        //         {
        //             CShared[y][x] += Creg[y][x];
        //         }
        //     }
        // }
        Aptr += blockDim.x * 5;
        Bptr += blockDim.x * N * 5;
    }

    if (tid == 0)
    {
        for (int y = 0; y < 4; y++) for (int x = 0; x < 5; x++)
            mat_c[(tileY * 4 + y) * N + (tileX * 5 + x)] = CShared[y][x];
    }
}

void mult_one_warp_per_tile_2(const float* mat_a, const float* mat_b, float* mat_c, int N)
{
    dim3 gridDim(N/5, N/4);
    mult_one_warp_per_tile_2_kernel<<<gridDim, 64>>>(mat_a, mat_b, mat_c, N);
    CUDA_CHK(cudaGetLastError());
    CUDA_CHK(cudaDeviceSynchronize());
}
